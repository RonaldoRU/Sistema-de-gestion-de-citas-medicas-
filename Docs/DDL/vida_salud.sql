-- =========================================================
-- BASE DE DATOS - SISTEMA WEB DE GESTIÓN DE CITAS MÉDICAS
-- CLÍNICA "VIDA SALUD"
-- PostgreSQL 14+
-- UAGRM - Sistemas de Información I (SI1) - Grupo 17 - Gestión 2/2026
-- Diseño v3: 36 casos de uso (CU01–CU36), 7 paquetes (P1–P7)
-- =========================================================
--
-- SINTAXIS DEL DOCUMENTO
--   Cada tabla lleva antes un comentario con: para qué sirve, qué casos de
--   uso implementa (numeración del Excel "Resumen 36 Casos de Uso") y las
--   columnas o restricciones que conviene mirar con atención.
--   Las clases del diagrama están en CamelCase (InformacionMedica); aquí las
--   tablas van en snake_case y en singular (informacion_medica).
--
-- NOTA SOBRE LAS LLAVES PRIMARIAS
--   Todas las PK son `bigint GENERATED BY DEFAULT AS IDENTITY`. Es el estándar
--   SQL para autoincrementales (reemplaza a SERIAL) y permite insertar sin
--   indicar el id, o con id explícito al cargar datos de prueba.
--   Excepción: las subclases de persona (paciente, medico,
--   personal_administrativo) NO tienen identidad propia: su PK es a la vez FK
--   a persona (herencia "tabla por subclase").
--
-- NOTA SOBRE LAS LLAVES FORÁNEAS
--   Todas las FK se declaran al final con ALTER TABLE, agrupadas por módulo,
--   y van `DEFERRABLE INITIALLY DEFERRED`: PostgreSQL las valida al terminar
--   la transacción, así se pueden cargar tablas que se referencian entre sí
--   (persona/paciente, cita/cita) en cualquier orden.
--   Regla de ON DELETE (sale del diagrama de clases):
--     CASCADE   -> composiciones (rombo relleno): la parte muere con el todo.
--     SET NULL  -> bitácora y referencias opcionales: se conserva el histórico.
--     RESTRICT  -> todo lo demás: no se borra lo que tiene historial; se usa
--                  baja lógica (columna `activo`), como piden CU09, CU15, CU19.
--
-- NOTA SOBRE LOS ENUM
--   Las 6 enumeraciones del diagrama se crean con CREATE TYPE ... AS ENUM.
--   Se eligió ENUM y no una tabla catálogo porque son listas cerradas que el
--   usuario no administra desde el sistema (los estados de una cita no se
--   "crean" desde una pantalla). El ENUM valida el dato en la base, ocupa
--   4 bytes y se lee igual que un texto. Si en el futuro hiciera falta un
--   valor nuevo: ALTER TYPE ... ADD VALUE.
--
-- EJECUCIÓN
--   El script se puede correr varias veces: empieza borrando y recreando el
--   esquema `vida_salud`. ¡Borra todos los datos de ese esquema!
--     psql -d <base> -f vida_salud.sql
-- =========================================================

DROP SCHEMA IF EXISTS vida_salud CASCADE;
CREATE SCHEMA vida_salud;
SET search_path TO vida_salud;

-- =========================================================
-- TIPOS ENUMERADOS (6 enumeraciones del diagrama)
-- =========================================================

-- CU04, CU09: BLOQUEADO lo pone el bloqueo por intentos fallidos;
-- INACTIVO es la baja lógica de la cuenta.
CREATE TYPE estado_usuario AS ENUM ('ACTIVO', 'INACTIVO', 'BLOQUEADO');

-- CU10: tipos de acción que registra la bitácora.
CREATE TYPE tipo_accion AS ENUM ('CREAR', 'MODIFICAR', 'ELIMINAR', 'LOGIN', 'LOGOUT', 'BLOQUEO', 'INACTIVAR', 'REGISTRAR', 'RENOVAR', 'REACTIVAR');

-- CU33: motivo del bloqueo de agenda.
CREATE TYPE tipo_bloqueo AS ENUM ('FERIADO', 'LICENCIA', 'OTRO');

-- CU25: máquina de estados de la cita.
CREATE TYPE estado_cita AS ENUM ('PROGRAMADA', 'CONFIRMADA', 'ATENDIDA', 'CANCELADA', 'INASISTENCIA');

-- CU34: estado de envío de un recordatorio.
CREATE TYPE estado_notificacion AS ENUM ('PENDIENTE', 'ENVIADA', 'FALLIDA');

-- CU27–CU30, CU36: tipos de reporte administrativo.
CREATE TYPE tipo_reporte AS ENUM ('CITAS_PERIODO', 'ATENCIONES_MEDICO_ESPECIALIDAD', 'CONTROL_ASISTENCIA', 'PACIENTES_REGISTRADOS');

-- =========================================================
-- MÓDULO 4 (BASE): PERSONA
-- Se crea primero porque usuario, paciente y medico dependen de ella.
-- =========================================================

-- Superclase abstracta Persona (herencia tabla por subclase).
-- Guarda los datos comunes de pacientes, médicos y personal administrativo,
-- para no repetir CI, nombres y contacto en tres tablas.
-- CU05, CU12, CU13, CU17.
--   ci      UNIQUE: no puede haber dos personas con el mismo carnet (CU12).
--   email   opcional (un paciente puede no tener correo); su unicidad sin
--           distinguir mayúsculas la da el índice persona_email_unico_ci.
--   activo  baja lógica (CU15, CU19): nunca se borra la fila.
CREATE TABLE "persona" (
  "id_persona" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ci" varchar(20) NOT NULL
    CONSTRAINT "persona_ci_unico" UNIQUE,
  "nombres" varchar(80) NOT NULL,
  "apellidos" varchar(80) NOT NULL,
  "telefono" varchar(20),
  "email" varchar(150),
  "activo" boolean NOT NULL DEFAULT true,
  "fecha_registro" timestamptz NOT NULL DEFAULT now()
);

-- Unicidad del correo sin distinguir mayúsculas: "Ana@mail.com" y
-- "ana@mail.com" son la misma casilla. Es parcial (WHERE email IS NOT NULL)
-- porque varias personas pueden no tener correo.
CREATE UNIQUE INDEX "persona_email_unico_ci"
  ON "persona" (lower("email")) WHERE "email" IS NOT NULL;

-- Búsqueda de pacientes y usuarios por nombre o apellido (CU06, CU13).
CREATE INDEX "persona_apellidos_nombres_idx" ON "persona" (lower("apellidos"), lower("nombres"));

-- =========================================================
-- MÓDULO 1: SEGURIDAD Y AUTENTICACIÓN (P1 · CU01–CU04)
-- MÓDULO 2: ADMINISTRACIÓN DE USUARIOS RBAC (P2 · CU05–CU09)
-- Se declaran juntos porque comparten la tabla usuario.
-- =========================================================

-- Rol del personal: Administrador, Recepcionista, Médico. CU05, CU08.
CREATE TABLE "rol" (
  "id_rol" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(50) NOT NULL
    CONSTRAINT "rol_nombre_unico" UNIQUE,
  "descripcion" text
);

-- Permisos de la "Matriz de Permisos" (CU08).
--   modulo     paquete al que pertenece la opción de menú (P1..P7).
--   ruta_menu  ruta o pantalla que habilita en el sistema web.
CREATE TABLE "permiso" (
  "id_permiso" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(80) NOT NULL
    CONSTRAINT "permiso_nombre_unico" UNIQUE,
  "modulo" varchar(60) NOT NULL,
  "ruta_menu" varchar(150)
);

-- Clase de asociación RolPermiso: Rol 0..* — 0..* Permiso "agrupa" (CU08).
-- fecha_asignacion: cuándo se otorgó el permiso al rol (DEFAULT now()).
-- PK compuesta: un rol no puede repetir el mismo permiso.
CREATE TABLE "rol_permiso" (
  "id_rol" bigint NOT NULL,
  "id_permiso" bigint NOT NULL,
  "fecha_asignacion" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "rol_permiso_pk" PRIMARY KEY ("id_rol", "id_permiso")
);

-- Cuenta de acceso del personal (no es la persona: Persona 1 — 0..1 Usuario).
-- CU01–CU09.
--   id_persona        UNIQUE: una persona tiene como máximo una cuenta.
--   id_rol            NOT NULL: cada usuario tiene exactamente 1 rol (CU05, CU08).
--   hash_contrasena   resultado de password_hash() de PHP; nunca la clave en claro.
--   estado            ACTIVO / INACTIVO (CU09) / BLOQUEADO (CU04).
--   intentos_fallidos contador de fallos consecutivos (CU04). CHECK >= 0.
--   bloqueado_hasta   fin del bloqueo temporal; NULL = no bloqueada.
CREATE TABLE "usuario" (
  "id_usuario" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_persona" bigint NOT NULL
    CONSTRAINT "usuario_persona_unica" UNIQUE,
  "id_rol" bigint NOT NULL,
  "nombre_usuario" varchar(50) NOT NULL,
  "hash_contrasena" varchar(255) NOT NULL,
  "estado" estado_usuario NOT NULL DEFAULT 'ACTIVO',
  "intentos_fallidos" smallint NOT NULL DEFAULT 0
    CONSTRAINT "usuario_intentos_fallidos_no_negativo" CHECK ("intentos_fallidos" >= 0),
  "bloqueado_hasta" timestamptz,
  "ultimo_acceso" timestamptz,
  "fecha_creacion" timestamptz NOT NULL DEFAULT now()
);

-- Unicidad del nombre de usuario sin distinguir mayúsculas: evita que
-- "Admin" y "admin" sean dos cuentas distintas (CU05).
CREATE UNIQUE INDEX "usuario_nombre_usuario_unico_ci" ON "usuario" (lower("nombre_usuario"));
CREATE INDEX "usuario_rol_idx" ON "usuario" ("id_rol");

-- Sesión de un usuario (composición Usuario 1 ◆— 0..* Sesion).
-- CU01 la crea, CU02 la cierra/revoca, CU09 revoca todas las sesiones activas.
--   id_sesion  identificador de sesión de PHP (session_id), por eso es texto.
--   activa     false cuando se cierra o se revoca.
CREATE TABLE "sesion" (
  "id_sesion" varchar(128) PRIMARY KEY,
  "id_usuario" bigint NOT NULL,
  "fecha_inicio" timestamptz NOT NULL DEFAULT now(),
  "ultima_actividad" timestamptz NOT NULL DEFAULT now(),
  "fecha_cierre" timestamptz,
  "activa" boolean NOT NULL DEFAULT true,
  "ip" varchar(45),
  CONSTRAINT "sesion_cierre_coherente"
    CHECK ("fecha_cierre" IS NULL OR "fecha_cierre" >= "fecha_inicio")
);

-- Índice parcial: CU09 busca "las sesiones activas de este usuario".
CREATE INDEX "sesion_usuario_activa_idx" ON "sesion" ("id_usuario") WHERE "activa";

-- Código/enlace de recuperación de contraseña (clase RecuperacionContrasena).
-- Composición Usuario 1 ◆— 0..* token_recuperacion. CU03.
--   token_hash  SHA-256 del código; el código en claro solo sale por correo,
--               así que leer esta tabla no permite cambiar ninguna clave.
--   usado       el código es de un solo uso.
--   CHECK       la expiración tiene que ser posterior a la emisión.
CREATE TABLE "token_recuperacion" (
  "id_token" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_usuario" bigint NOT NULL,
  "token_hash" varchar(64) NOT NULL
    CONSTRAINT "token_recuperacion_hash_unico" UNIQUE,
  "fecha_generacion" timestamptz NOT NULL DEFAULT now(),
  "fecha_expiracion" timestamptz NOT NULL,
  "usado" boolean NOT NULL DEFAULT false,
  CONSTRAINT "token_recuperacion_expiracion_positiva"
    CHECK ("fecha_expiracion" > "fecha_generacion")
);

CREATE INDEX "token_recuperacion_usuario_idx" ON "token_recuperacion" ("id_usuario", "fecha_generacion" DESC);

-- Subclase PersonalAdministrativo de Persona (Administrador / Recepcionista).
-- Supuesto del diseño: existe para que todo el personal sea una Persona.
--   id_persona  PK y FK a persona (tabla por subclase).
CREATE TABLE "personal_administrativo" (
  "id_persona" bigint PRIMARY KEY,
  "cargo" varchar(60) NOT NULL
);

-- =========================================================
-- MÓDULO 3: AUDITORÍA Y BITÁCORA (P3 · CU10–CU11)
-- =========================================================

-- Registro inmutable de operaciones críticas. CU10 (trigger/middleware la
-- llena), CU11 (consulta con filtros por usuario, módulo, acción y fechas).
--   id_usuario  admite NULL: un intento de login fallido de un usuario que no
--               existe no tiene usuario (CU04). Con ON DELETE SET NULL se
--               conserva el historial aunque se borre la cuenta.
CREATE TABLE "bitacora" (
  "id_bitacora" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_usuario" bigint,
  "fecha_hora" timestamptz NOT NULL DEFAULT now(),
  "modulo" varchar(60) NOT NULL,
  "tipo_accion" tipo_accion NOT NULL,
  "tabla_afectada" varchar(60),
  "id_registro_afectado" bigint,
  "detalle" text,
  "ip" varchar(45)
);

-- CU11 ordena en cronológico inverso y filtra por usuario/acción.
CREATE INDEX "bitacora_fecha_idx" ON "bitacora" ("fecha_hora" DESC);
CREATE INDEX "bitacora_usuario_fecha_idx" ON "bitacora" ("id_usuario", "fecha_hora" DESC);
CREATE INDEX "bitacora_accion_idx" ON "bitacora" ("tipo_accion");

-- =========================================================
-- MÓDULO 4: GESTIÓN DE PACIENTES (P4 · CU12–CU15, CU31–CU32)
-- =========================================================

-- Subclase Paciente de Persona. CU12–CU15.
--   id_persona  PK y FK a persona (los datos comunes y el CI único están allí).
--   codigo      código identificador único del paciente.
--   sexo        'M' o 'F' (CHECK).
CREATE TABLE "paciente" (
  "id_persona" bigint PRIMARY KEY,
  "codigo" varchar(15) NOT NULL
    CONSTRAINT "paciente_codigo_unico" UNIQUE,
  "sexo" char(1) NOT NULL
    CONSTRAINT "paciente_sexo_valido" CHECK ("sexo" IN ('M', 'F')),
  "fecha_nacimiento" date NOT NULL
    CONSTRAINT "paciente_fecha_nacimiento_pasada" CHECK ("fecha_nacimiento" <= CURRENT_DATE),
  "direccion" varchar(200)
);

-- Información médica básica (composición Paciente 1 ◆— 0..1). CU31.
--   id_paciente  UNIQUE: un paciente tiene como máximo una ficha.
--   tipo_sangre  CHECK con los 8 grupos sanguíneos.
CREATE TABLE "informacion_medica" (
  "id_informacion" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_paciente" bigint NOT NULL
    CONSTRAINT "informacion_medica_paciente_unico" UNIQUE,
  "tipo_sangre" varchar(3)
    CONSTRAINT "informacion_medica_tipo_sangre_valido"
      CHECK ("tipo_sangre" IN ('A+','A-','B+','B-','AB+','AB-','O+','O-')),
  "alergias" text,
  "enfermedades_cronicas" text,
  "medicamentos_habituales" text,
  "antecedentes_relevantes" text,
  "observaciones" text,
  "fecha_actualizacion" timestamptz NOT NULL DEFAULT now()
);

-- Contactos de emergencia (composición Paciente 1 ◆— 0..*). CU32.
CREATE TABLE "contacto_emergencia" (
  "id_contacto" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_paciente" bigint NOT NULL,
  "nombre_completo" varchar(150) NOT NULL,
  "parentesco" varchar(40) NOT NULL,
  "telefono" varchar(20) NOT NULL
);

CREATE INDEX "contacto_emergencia_paciente_idx" ON "contacto_emergencia" ("id_paciente");

-- =========================================================
-- MÓDULO 5: GESTIÓN MÉDICA Y HORARIOS (P5 · CU16–CU19, CU33)
-- =========================================================

-- Catálogo de especialidades. CU16.
--   nombre  único sin distinguir mayúsculas ni espacios extremos
--           ("Pediatría" = " pediatría "), ver índice.
CREATE TABLE "especialidad" (
  "id_especialidad" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(80) NOT NULL,
  "descripcion" varchar(200),
  "activo" boolean NOT NULL DEFAULT true
);

CREATE UNIQUE INDEX "especialidad_nombre_unico_ci" ON "especialidad" (lower(btrim("nombre")));

-- Subclase Medico de Persona. CU17, CU19.
--   id_persona  PK y FK a persona.
--   matricula   registro profesional, único.
CREATE TABLE "medico" (
  "id_persona" bigint PRIMARY KEY,
  "codigo" varchar(15) NOT NULL
    CONSTRAINT "medico_codigo_unico" UNIQUE,
  "matricula" varchar(30) NOT NULL
    CONSTRAINT "medico_matricula_unica" UNIQUE
);

-- Clase de asociación MedicoEspecialidad: Medico 0..* — 1..* Especialidad "ejerce" (CU17).
-- fecha_asignacion: cuándo se asignó la especialidad al médico (DEFAULT now()).
-- La regla "al menos 1 especialidad" no se puede forzar con una FK; la
-- valida la aplicación al guardar el médico.
CREATE TABLE "medico_especialidad" (
  "id_medico" bigint NOT NULL,
  "id_especialidad" bigint NOT NULL,
  "fecha_asignacion" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "medico_especialidad_pk" PRIMARY KEY ("id_medico", "id_especialidad")
);

CREATE INDEX "medico_especialidad_especialidad_idx" ON "medico_especialidad" ("id_especialidad");

-- Jornada de atención por día de la semana (composición Medico 1 ◆— 0..*). CU18.
--   dia_semana            1 = lunes ... 7 = domingo (CHECK).
--   CHECK hora_fin > hora_inicio: evita horarios ilógicos.
--   duracion_bloque_min   30 por defecto (bloques fijos de 30 minutos).
--   La no superposición de franjas del mismo médico se valida en la
--   aplicación (Horario.validarSuperposicion()).
CREATE TABLE "horario" (
  "id_horario" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_medico" bigint NOT NULL,
  "dia_semana" smallint NOT NULL
    CONSTRAINT "horario_dia_semana_valido" CHECK ("dia_semana" BETWEEN 1 AND 7),
  "hora_inicio" time NOT NULL,
  "hora_fin" time NOT NULL,
  "duracion_bloque_min" smallint NOT NULL DEFAULT 30
    CONSTRAINT "horario_duracion_bloque_positiva" CHECK ("duracion_bloque_min" > 0),
  "activo" boolean NOT NULL DEFAULT true,
  CONSTRAINT "horario_rango_valido" CHECK ("hora_fin" > "hora_inicio")
);

CREATE INDEX "horario_medico_dia_idx" ON "horario" ("id_medico", "dia_semana");

-- Bloqueo de agenda por feriados o licencias (Medico 0..1 — 0..*). CU33.
--   id_medico      NULL = feriado general que afecta a toda la clínica.
--   aplica_a_todos debe ser coherente con id_medico (CHECK "o uno o el otro"):
--                  true  -> id_medico NULL (feriado general)
--                  false -> id_medico obligatorio (licencia de un médico)
--   CHECK fecha_fin >= fecha_inicio.
CREATE TABLE "bloqueo_agenda" (
  "id_bloqueo" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_medico" bigint,
  "fecha_inicio" date NOT NULL,
  "fecha_fin" date NOT NULL,
  "motivo" varchar(200) NOT NULL,
  "tipo" tipo_bloqueo NOT NULL,
  "aplica_a_todos" boolean NOT NULL DEFAULT false,
  CONSTRAINT "bloqueo_agenda_rango_valido" CHECK ("fecha_fin" >= "fecha_inicio"),
  CONSTRAINT "bloqueo_agenda_alcance_coherente" CHECK (
    ("aplica_a_todos" AND "id_medico" IS NULL)
    OR
    (NOT "aplica_a_todos" AND "id_medico" IS NOT NULL)
  )
);

-- CU20/CU22 preguntan "¿está bloqueada esta fecha para este médico?".
CREATE INDEX "bloqueo_agenda_medico_fechas_idx" ON "bloqueo_agenda" ("id_medico", "fecha_inicio", "fecha_fin");

-- =========================================================
-- MÓDULO 6: GESTIÓN DE CITAS (P6 · CU20–CU26, CU34–CU35)
-- =========================================================

-- Cita médica. CU20–CU26, CU34, CU35.
--   codigo               correlativo CM-0001 (CHECK de formato, UNIQUE).
--   estado               máquina de estados (CU25).
--   motivo_cancelacion   obligatorio si estado = CANCELADA (CU24, CHECK).
--   fecha_hora_atencion  se llena al marcar ATENDIDA (CU35).
--   id_usuario_registro  quién programó la cita (trazabilidad).
--   id_cita_origen       autoasociación "reprogramadaDe": la cita nueva
--                        apunta a la original (CU23).
--   CHECK hora_fin > hora_inicio.
CREATE TABLE "cita" (
  "id_cita" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "codigo" varchar(12) NOT NULL
    CONSTRAINT "cita_codigo_unico" UNIQUE
    CONSTRAINT "cita_codigo_formato" CHECK ("codigo" ~ '^CM-[0-9]{4,}$'),
  "id_paciente" bigint NOT NULL,
  "id_medico" bigint NOT NULL,
  "id_especialidad" bigint NOT NULL,
  "id_usuario_registro" bigint NOT NULL,
  "id_cita_origen" bigint,
  "fecha" date NOT NULL,
  "hora_inicio" time NOT NULL,
  "hora_fin" time NOT NULL,
  "motivo_consulta" varchar(200) NOT NULL,
  "estado" estado_cita NOT NULL DEFAULT 'PROGRAMADA',
  "motivo_cancelacion" varchar(200),
  "observacion_atencion" text,
  "fecha_hora_atencion" timestamptz,
  "fecha_creacion" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "cita_rango_valido" CHECK ("hora_fin" > "hora_inicio"),
  CONSTRAINT "cita_cancelada_con_motivo" CHECK (
    "estado" <> 'CANCELADA' OR ("motivo_cancelacion" IS NOT NULL AND btrim("motivo_cancelacion") <> '')
  ),
  CONSTRAINT "cita_atendida_con_fecha" CHECK (
    "estado" <> 'ATENDIDA' OR "fecha_hora_atencion" IS NOT NULL
  ),
  CONSTRAINT "cita_no_es_su_propio_origen" CHECK ("id_cita_origen" IS NULL OR "id_cita_origen" <> "id_cita")
);

-- CU22 - Prevenir citas duplicadas (control de concurrencia).
-- Índice único PARCIAL: un médico no puede tener dos citas que empiecen a la
-- misma hora del mismo día, salvo que una esté CANCELADA (la cancelación
-- libera el cupo, CU24). Si dos recepcionistas reservan a la vez el mismo
-- bloque, la segunda inserción falla aquí aunque la validación de PHP no lo
-- haya detectado. Como los bloques son fijos de 30 min, comparar la hora de
-- inicio basta para impedir la superposición.
CREATE UNIQUE INDEX "cita_medico_bloque_unico"
  ON "cita" ("id_medico", "fecha", "hora_inicio")
  WHERE "estado" <> 'CANCELADA';

CREATE INDEX "cita_paciente_fecha_idx" ON "cita" ("id_paciente", "fecha" DESC);   -- CU14 historial
CREATE INDEX "cita_medico_fecha_idx" ON "cita" ("id_medico", "fecha");           -- CU20, CU26 agenda
CREATE INDEX "cita_fecha_estado_idx" ON "cita" ("fecha", "estado");              -- CU27, CU29 reportes
CREATE INDEX "cita_especialidad_idx" ON "cita" ("id_especialidad");              -- CU28

-- Historial de cambios de estado y reprogramaciones
-- (composición Cita 1 ◆— 1..*). CU23, CU24, CU25, CU35.
--   estado_anterior  NULL en el primer registro (la cita nace PROGRAMADA).
--   fecha_anterior / hora_anterior  se guardan al reprogramar (CU23).
--   id_usuario       quién hizo el cambio (Usuario 1 — 0..*).
CREATE TABLE "historial_estado_cita" (
  "id_historial" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_cita" bigint NOT NULL,
  "id_usuario" bigint NOT NULL,
  "estado_anterior" estado_cita,
  "estado_nuevo" estado_cita NOT NULL,
  "fecha_anterior" date,
  "hora_anterior" time,
  "motivo" varchar(200),
  "fecha_cambio" timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX "historial_estado_cita_cita_idx" ON "historial_estado_cita" ("id_cita", "fecha_cambio");

-- Recordatorios de cita por TELÉFONO (composición Cita 1 ◆— 0..*). CU34.
--   Flujo CU34: el sistema genera la lista de recordatorios del día siguiente
--   en recepción (estado PENDIENTE); la recepcionista llama al paciente y
--   marca el resultado. Canal único: teléfono (por eso no hay columna canal).
--   estado            PENDIENTE = pendiente de llamar;
--                     ENVIADA   = llamado / cita confirmada con el paciente;
--                     FALLIDA   = no contestó o paciente sin teléfono.
--   id_usuario_gestion recepcionista que hizo la llamada (NULL si PENDIENTE).
--   fecha_envio       fecha y hora de la (última) llamada; NULL si PENDIENTE.
--   intentos          número de llamadas realizadas (Notificacion.reintentar()).
CREATE TABLE "notificacion" (
  "id_notificacion" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_cita" bigint NOT NULL,
  "id_usuario_gestion" bigint,
  "mensaje" text NOT NULL,
  "fecha_programada" timestamptz NOT NULL,
  "fecha_envio" timestamptz,
  "estado" estado_notificacion NOT NULL DEFAULT 'PENDIENTE',
  "intentos" smallint NOT NULL DEFAULT 0
    CONSTRAINT "notificacion_intentos_no_negativos" CHECK ("intentos" >= 0),
  CONSTRAINT "notificacion_enviada_con_fecha" CHECK (
    "estado" <> 'ENVIADA' OR "fecha_envio" IS NOT NULL
  ),
  -- Toda llamada realizada (ENVIADA o FALLIDA) registra quién y cuándo llamó.
  CONSTRAINT "notificacion_gestionada_con_usuario" CHECK (
    "estado" = 'PENDIENTE' OR ("id_usuario_gestion" IS NOT NULL AND "fecha_envio" IS NOT NULL AND "intentos" >= 1)
  )
);

-- Lista de llamadas pendientes que recepción ve en CU34.
CREATE INDEX "notificacion_pendiente_idx" ON "notificacion" ("fecha_programada") WHERE "estado" = 'PENDIENTE';
CREATE INDEX "notificacion_usuario_gestion_idx" ON "notificacion" ("id_usuario_gestion");
CREATE INDEX "notificacion_cita_idx" ON "notificacion" ("id_cita");

-- =========================================================
-- MÓDULO 7: REPORTES (P7 · CU27–CU30, CU36)
-- =========================================================

-- Registro de reportes generados. CU27–CU30, CU36.
-- Supuesto: guardar los reportes es opcional; sirve para saber quién generó
-- qué y con qué filtros. Los datos del reporte se calculan con consultas
-- sobre cita, paciente, medico y especialidad (no se copian aquí).
--   filtros  jsonb con los filtros usados (médico, especialidad, estado...).
--   formato  PDF o CSV cuando se exporta (CU30); NULL si solo se visualizó.
CREATE TABLE "reporte" (
  "id_reporte" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_usuario" bigint NOT NULL,
  "tipo" tipo_reporte NOT NULL,
  "fecha_desde" date,
  "fecha_hasta" date,
  "filtros" jsonb,
  "formato" varchar(4)
    CONSTRAINT "reporte_formato_valido" CHECK ("formato" IN ('PDF', 'CSV')),
  "fecha_generacion" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "reporte_rango_valido" CHECK (
    "fecha_desde" IS NULL OR "fecha_hasta" IS NULL OR "fecha_hasta" >= "fecha_desde"
  )
);

CREATE INDEX "reporte_usuario_fecha_idx" ON "reporte" ("id_usuario", "fecha_generacion" DESC);

