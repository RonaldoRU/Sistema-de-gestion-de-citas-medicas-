-- -------------------------------------------------------------
-- CLASE: Persona (Superclase abstracta)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.persona CASCADE;
CREATE TABLE vida_salud.persona (
    id_persona BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci VARCHAR(20) NOT NULL CONSTRAINT persona_ci_unico UNIQUE,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(80) NOT NULL,
    telefono VARCHAR(20),
    email VARCHAR(150),
    activo BOOLEAN NOT NULL DEFAULT true,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Rol (Roles del Sistema RBAC)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.rol CASCADE;
CREATE TABLE vida_salud.rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL CONSTRAINT rol_nombre_unico UNIQUE,
    descripcion VARCHAR(200),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Permiso (Permisos del Sistema RBAC)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.permiso CASCADE;
CREATE TABLE vida_salud.permiso (
    id_permiso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CONSTRAINT permiso_nombre_unico UNIQUE,
    descripcion VARCHAR(200),
    modulo VARCHAR(50) NOT NULL,
    ruta_menu VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE ASOCIATIVA: RolPermiso (M:N)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.rol_permiso CASCADE;
CREATE TABLE vida_salud.rol_permiso (
    id_rol BIGINT NOT NULL,
    id_permiso BIGINT NOT NULL,
    PRIMARY KEY (id_rol, id_permiso)
);

-- -------------------------------------------------------------
-- CLASE: Usuario (Cuenta de acceso y autenticación)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.usuario CASCADE;
CREATE TABLE vida_salud.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_persona BIGINT NOT NULL CONSTRAINT usuario_persona_unica UNIQUE,
    id_rol BIGINT NOT NULL,
    nombre_usuario VARCHAR(50) NOT NULL CONSTRAINT usuario_nombre_unico UNIQUE,
    hash_contrasena VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',
    intentos_fallidos SMALLINT NOT NULL DEFAULT 0,
    bloqueado_hasta TIMESTAMPTZ,
    fecha_bloqueo TIMESTAMPTZ,
    ultimo_acceso TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    remember_token VARCHAR(100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Sesion (Tokens de sesión activa)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.sesion CASCADE;
CREATE TABLE vida_salud.sesion (
    id_sesion VARCHAR(128) PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultima_actividad TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_cierre TIMESTAMPTZ,
    activa BOOLEAN NOT NULL DEFAULT true,
    ip VARCHAR(45),
    ip_address VARCHAR(45),
    user_agent TEXT,
    payload TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: TokenRecuperacion (Recuperación de contraseña)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.token_recuperacion CASCADE;
CREATE TABLE vida_salud.token_recuperacion (
    id_token BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL CONSTRAINT token_hash_unico UNIQUE,
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT false
);

DROP TABLE IF EXISTS vida_salud.recuperacion_contrasena CASCADE;
CREATE TABLE vida_salud.recuperacion_contrasena (
    id_recuperacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL CONSTRAINT recup_hash_unico UNIQUE,
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_expiracion TIMESTAMPTZ NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT false
);

-- -------------------------------------------------------------
-- CLASE: PersonalAdministrativo (Subclase de Persona)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.personal_administrativo CASCADE;
CREATE TABLE vida_salud.personal_administrativo (
    id_persona BIGINT PRIMARY KEY,
    cargo VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Bitacora (Auditoría integral)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.bitacora CASCADE;
CREATE TABLE vida_salud.bitacora (
    id_bitacora BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    modulo VARCHAR(60) NOT NULL,
    tipo_accion VARCHAR(30) NOT NULL,
    tabla_afectada VARCHAR(60),
    id_registro_afectado BIGINT,
    descripcion VARCHAR(255) DEFAULT '',
    detalle TEXT,
    detalle_anterior JSONB,
    detalle_nuevo JSONB,
    ip VARCHAR(45),
    direccion_ip VARCHAR(45),
    navegador VARCHAR(255) DEFAULT 'Chrome / Mozilla',
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Paciente (Subclase de Persona)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.paciente CASCADE;
CREATE TABLE vida_salud.paciente (
    id_persona BIGINT PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL CONSTRAINT paciente_codigo_unico UNIQUE,
    sexo CHAR(1) NOT NULL CONSTRAINT paciente_sexo_check CHECK (sexo IN ('M', 'F', 'O')),
    fecha_nacimiento DATE NOT NULL,
    direccion VARCHAR(200),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: InformacionMedica (Composición 1:1 con Paciente)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.informacion_medica CASCADE;
CREATE TABLE vida_salud.informacion_medica (
    id_informacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL CONSTRAINT info_medica_paciente_unica UNIQUE,
    tipo_sangre VARCHAR(5),
    grupo_sanguineo VARCHAR(5),
    alergias TEXT,
    enfermedades_cronicas TEXT,
    medicamentos_habituales TEXT,
    antecedentes_relevantes TEXT,
    antecedentes TEXT,
    observaciones TEXT,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: ContactoEmergencia (Composición 1:N con Paciente)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.contacto_emergencia CASCADE;
CREATE TABLE vida_salud.contacto_emergencia (
    id_contacto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL,
    nombre_completo VARCHAR(150),
    nombre VARCHAR(150),
    parentesco VARCHAR(50) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Especialidad (Catálogo de Especialidades y Aranceles)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.especialidad CASCADE;
CREATE TABLE vida_salud.especialidad (
    id_especialidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL,
    descripcion VARCHAR(255),
    costo DECIMAL(10,2) NOT NULL DEFAULT 120.00,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: Medico (Subclase de Persona)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.medico CASCADE;
CREATE TABLE vida_salud.medico (
    id_persona BIGINT PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL CONSTRAINT medico_codigo_unico UNIQUE,
    matricula VARCHAR(30) NOT NULL CONSTRAINT medico_matricula_unica UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE ASOCIATIVA: MedicoEspecialidad (M:N)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.medico_especialidad CASCADE;
CREATE TABLE vida_salud.medico_especialidad (
    id_medico BIGINT NOT NULL,
    id_especialidad BIGINT NOT NULL,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (id_medico, id_especialidad)
);

-- -------------------------------------------------------------
-- CLASE: Horario (Disponibilidad médica semanal en bloques de 15 min)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.horario CASCADE;
CREATE TABLE vida_salud.horario (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico BIGINT NOT NULL,
    dia_semana SMALLINT NOT NULL CONSTRAINT horario_dia_check CHECK (dia_semana BETWEEN 1 AND 7),
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    duracion_bloque_min SMALLINT NOT NULL DEFAULT 15,
    activo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT horario_rango_check CHECK (hora_fin > hora_inicio)
);

-- -------------------------------------------------------------
-- CLASE: BloqueoAgenda (Feriados y licencias)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.bloqueo_agenda CASCADE;
CREATE TABLE vida_salud.bloqueo_agenda (
    id_bloqueo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico BIGINT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo VARCHAR(200) NOT NULL,
    tipo VARCHAR(30) NOT NULL DEFAULT 'FERIADO',
    tipo_bloqueo vida_salud.tipo_bloqueo,
    aplica_a_todos BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT bloqueo_fechas_check CHECK (fecha_fin >= fecha_inicio)
);

-- -------------------------------------------------------------
-- CLASE: Cita (Ficha médica de atención)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.cita CASCADE;
CREATE TABLE vida_salud.cita (
    id_cita BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL CONSTRAINT cita_codigo_unico UNIQUE,
    id_paciente BIGINT NOT NULL,
    id_medico BIGINT NOT NULL,
    id_especialidad BIGINT NOT NULL,
    id_usuario_registro BIGINT NOT NULL,
    id_cita_origen BIGINT,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PROGRAMADA',
    origen VARCHAR(20) NOT NULL DEFAULT 'WEB',
    motivo_consulta VARCHAR(200) NOT NULL DEFAULT 'Consulta médica',
    motivo_cancelacion VARCHAR(200),
    observacion_atencion TEXT,
    observaciones_atencion TEXT,
    fecha_hora_atencion TIMESTAMPTZ,
    expira_en TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT cita_horas_check CHECK (hora_fin > hora_inicio)
);

-- -------------------------------------------------------------
-- CLASE: HistorialEstadoCita (Trazabilidad)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.historial_estado_cita CASCADE;
CREATE TABLE vida_salud.historial_estado_cita (
