-- -------------------------------------------------------------
-- CLASE: Pago (Transacción financiera en Bs)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.pago CASCADE;
CREATE TABLE vida_salud.pago (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL,
    id_usuario_registro BIGINT,
    monto DECIMAL(10,2) NOT NULL,
    moneda VARCHAR(5) NOT NULL DEFAULT 'BOB',
    metodo VARCHAR(30) NOT NULL DEFAULT 'QR',
    estado VARCHAR(20) NOT NULL DEFAULT 'APROBADO',
    referencia_externa VARCHAR(100) CONSTRAINT pago_ref_unica UNIQUE,
    nit_ci VARCHAR(30),
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------------
-- CLASE: ComprobantePago (Recibo digital oficial)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.comprobante_pago CASCADE;
CREATE TABLE vida_salud.comprobante_pago (
    id_comprobante BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL CONSTRAINT comprobante_pago_unico UNIQUE,
    numero VARCHAR(50) NOT NULL CONSTRAINT comprobante_numero_unico UNIQUE,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT now(),
    monto_total DECIMAL(10,2) NOT NULL,
    ruta_archivo VARCHAR(255)
);

-- -------------------------------------------------------------
-- CLASE: Reembolso (Devolución por cancelación)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.reembolso CASCADE;
CREATE TABLE vida_salud.reembolso (
    id_reembolso BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pago BIGINT NOT NULL,
    id_usuario_autoriza BIGINT,
    monto DECIMAL(10,2) NOT NULL,
    motivo VARCHAR(255) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'SOLICITADO',
    fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_procesado TIMESTAMPTZ,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
    referencia_externa VARCHAR(100)
);

-- -------------------------------------------------------------
-- CLASE: Reporte (Reportes emitidos)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.reporte CASCADE;
CREATE TABLE vida_salud.reporte (
    id_reporte BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT,
    id_usuario_generador BIGINT,
    tipo VARCHAR(60) NOT NULL DEFAULT 'CITAS_PERIODO',
    tipo_reporte vida_salud.tipo_reporte,
    fecha_desde DATE,
    fecha_hasta DATE,
    filtros JSONB,
    parametros JSONB,
    formato VARCHAR(10) DEFAULT 'PDF',
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    ruta_archivo VARCHAR(255)
);

