-- -------------------------------------------------------------
-- CLASE: Notificacion (Avisos y recordatorios)
-- -------------------------------------------------------------
DROP TABLE IF EXISTS vida_salud.notificacion CASCADE;
CREATE TABLE vida_salud.notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita BIGINT NOT NULL,
    id_usuario_gestion BIGINT,
    tipo_canal VARCHAR(20) NOT NULL DEFAULT 'EMAIL',
